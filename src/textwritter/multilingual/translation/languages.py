# Human-readable Category Labels for UI Grouping
CATEGORY_LABELS: Dict[str, str] = {
    "south_indian": "🌴 South Indian Languages",
    "indian": "🇮🇳 Indian Regional Languages",
    "indigenous_low_resource": "🌿 Indigenous & Low-Resource Languages",
    "african": "🌍 African Languages",
    "european": "🏰 European Languages",
    "asian": "🌏 Other Asian Languages",
}


def get_translation_language(code: str) -> Optional[TranslationLanguage]:
    """Retrieve language metadata by ISO code (case-insensitive)."""
    return TRANSLATION_LANGUAGES.get(code.lower())


def get_grouped_languages() -> Dict[str, List[Dict]]:
    """Return dictionary of categories mapped to serializable language dictionaries."""
    groups: Dict[str, List[Dict]] = {}
    for cat_key, cat_label in CATEGORY_LABELS.items():
        groups[cat_key] = []
        for lang in TRANSLATION_LANGUAGES.values():
            if lang.category == cat_key:
                groups[cat_key].append({
                    "code": lang.code,
                    "name": lang.name,
                    "native_name": lang.native_name,
                    "script": lang.script,
                    "category": lang.category,
                    "category_label": cat_label,
                    "is_low_resource": lang.is_low_resource,
                    "is_supported": lang.is_supported,
                    "handwriting_supported": lang.handwriting_supported,
                    "direction": lang.direction,
                    "notes": lang.notes,
                })
    return groups
