"""Comprehensive Multilingual Translation Language Registry for Text_Writter Studio.

Provides authoritative language definitions, categories, scripts, ISO codes,
NLLB-200 BCP-47 codes, IndicTrans2 codes, Google MADLAD-400 codes,
low-resource indicators, and handwriting font compatibility.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple


@dataclass(frozen=True)
class TranslationLanguage:
    code: str                     # ISO 639-1 or 639-3 code
    name: str                     # English name
    native_name: str              # Native script name
    script: str                   # Unicode script family
    category: str                 # indian, south_indian, asian, european, african, indigenous_low_resource
    nllb_code: Optional[str]      # Meta NLLB-200 BCP-47 code (e.g. hin_Deva, tam_Taml, cym_Latn)
    indictrans_code: Optional[str]# AI4Bharat IndicTrans2 code
    madlad_code: Optional[str]    # Google MADLAD-400 code
    is_low_resource: bool         # Low-resource or indigenous language
    is_supported: bool            # True if supported by at least one pretrained model
    handwriting_supported: bool   # True if Text_Writter font stack has handwriting font for script
    direction: str = "ltr"        # "ltr" or "rtl"
    notes: str = ""               # Status / model availability details


